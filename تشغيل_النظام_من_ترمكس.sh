#!/data/data/com.termux/files/usr/bin/bash
# ==============================================================================
# سكربت التشغيل الموحد لنظام النشر الجامعي الذكي (تيليجرام + تويتر + العقل المدبر)
# تشغيل كل شيء بواجهة ويب واحدة موحدة على الهاتف (Termux)
# حفظ وتحديث مجلد «ملف_النشر» في وحدة التخزين الداخلية للهاتف (مجلد التنزيلات)
# ==============================================================================

set -e

GREEN='\033[0;32m'
SKY='\033[0;36m'
YELLOW='\033[1;33m'
PURPLE='\033[0;35m'
NC='\033[0m'

clear
echo -e "${SKY}================================================================================${NC}"
echo -e "${GREEN}  👑 منظومة النشر الجامعي الأكاديمي الموحدة (Termux Pro)${NC}"
echo -e "${SKY}  تيليجرام + تويتر (X Multi-Account) + استوديو الصور + العقل المدبر${NC}"
echo -e "${SKY}  المشرف العام: @M_S_F_G | المنظومة: ملف النشر الموحد${NC}"
echo -e "${SKY}================================================================================${NC}\n"

# 1. الانتقال لمجلد المشروع
cd "$(dirname "$0")"

# 2. التأكد من صلاحية وحدة التخزين الداخلية للهاتف
if [ ! -d "$HOME/storage/downloads" ] && [ ! -d "/sdcard/Download" ]; then
    echo -e "${YELLOW}🔑 طلب إذن الوصول لوحدة التخزين الداخلية للهاتف (مجلد Downloads)...${NC}"
    termux-setup-storage 2>/dev/null || true
    sleep 1
fi

# 3. سحب التحديثات من GitHub
echo -e "${YELLOW}📡 فحص وسحب أحدث التحديثات من GitHub...${NC}"
git pull origin master 2>/dev/null || true

# 4. بناء ومزامنة حزمة «ملف_النشر» في وحدة التخزين الداخلية (Download/ملف_النشر)
echo -e "\n${PURPLE}📂 مزامنة وإنشاء هيكل «ملف_النشر» في مجلد التنزيلات بالهاتف:${NC}"
echo -e "   ├── تويتر/ (الحسابات، الكوكيز، استوديو البطاقات، وسجل الردود)"
echo -e "   ├── تيليجرام/ (إعدادات البوت، القنوات، اليوزربوت، والوسائط)"
echo -e "   ├── ملفات_الجامعات/ (جامعة نجران، الملك سعود، AUM)"
echo -e "   ├── العقل_المدبر/ (النواة الإدراكية، القواعد، وقضايا الطلاب)"
echo -e "   └── سجل_الرقابة_والمنشورات/ (المقبولة والمرفوضة والأفكار)"

python3 -c "
import database as db
import publish_files_manager as pfm
res = pfm.build_and_sync_publish_package()
print('   ✅ تمت المزامنة بنجاح في:', res.get('synced_locations', []))
" 2>/dev/null || true

echo -e "\n${GREEN}================================================================================${NC}"
echo -e "${GREEN}  🚀 انطلاق المنظومة بالواجهة الموحدة الشاملة!${NC}"
echo -e "${SKY}  🌐 افتح المتصفح على هاتفك (Chrome أو Brave) وادخل الرابط:${NC}"
echo -e "${YELLOW}     👉 http://localhost:3000${NC}"
echo -e "${SKY}  📁 مسار ملفاتك في الهاتف: /sdcard/Download/ملف_النشر${NC}"
echo -e "${GREEN}================================================================================${NC}\n"

# 5. تشغيل واجهة الويب والبوت معاً بواجهة واحدة
if command -v npm &>/dev/null; then
    exec npm run dev
else
    echo -e "${YELLOW}⚠️ لم يتم العثور على npm؛ تشغيل محرك بايثون وتيليجرام وتويتر المباشر...${NC}"
    exec python3 main.py
fi
