#!/bin/bash
# ==============================================================================
# سكربت تشغيل واجهة الويب فقط (Web UI & Dashboard Only)
# يعمل على المنفذ 3000 بشكل منفصل تماماً دون تشغيل محرك بايثون في الخلفية
# مناسب للاستخدام عندما ترغب في تصفح وتعديل الإعدادات دون تشغيل البوت
# ==============================================================================

set -e

GREEN='\033[0;32m'
SKY='\033[0;36m'
YELLOW='\033[1;33m'
NC='\033[0m'

cd "$(dirname "$0")"

echo -e "${SKY}==================================================================${NC}"
echo -e "${GREEN}  🌐 تشغيل واجهة الويب ولوحة التحكم المستقلة (Web UI Only)${NC}"
echo -e "${SKY}  المنفذ: http://localhost:3000 | النمط: منفصل ومستقل 100%${NC}"
echo -e "${SKY}==================================================================${NC}\n"

# ضبط بيئة العمل لتعطيل تشغيل بايثون المدمج لمنع أي تداخل
export RUN_PYTHON_WORKER="false"

if command -v npm &>/dev/null; then
    exec npm run dev
else
    echo -e "${YELLOW}❌ npm غير متوفر في هذه البيئة. يرجى تثبيت nodejs.${NC}"
    exit 1
fi
